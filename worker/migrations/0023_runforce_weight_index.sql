-- RUNFORCE 가중치(만점)를 후반 대회일수록 점진적으로 키웁니다: i번째로 집계된 대회의
-- 만점은 300000 * 1.05^(i-1)입니다. weight_index가 그 i(1부터 시작)입니다.
--
-- i는 "대회 날짜" 순이 아니라 "RUNFORCE에 등록된 순서"입니다 — 등록 시점에 값이 확정되고
-- 그 뒤로 절대 안 바뀌어야, 이미 계산된 대회는 재계산하지 않는다는 이 기능의 핵심 불변식이
-- 유지되기 때문입니다(나중에 과거 대회를 추가해도 기존 회원 총점이 소급해서 흔들리지 않음).
-- 실제 점수는 등록 시점에 이 가중치로 계산해 runforce_results.score에 이미 반영해 넣으므로,
-- 이 컬럼은 "그 대회가 몇 번째였는지"를 보여주고 다음 번호를 정하는 용도입니다.
--
-- Div1/Div2로 짝지어진 대회는 한 라운드이므로 같은 weight_index를 공유합니다(둘 중 어느
-- 쪽 점수를 가져가든 만점이 같도록) — worker/src/lib/runforce.ts::addTargetContest 참고.
--
-- 기존 행은 전부 1로 채웁니다: 지금까지는 만점이 300000 고정이었으므로 1.05^0 = 1과 정확히
-- 같아서, 이미 저장된 점수와 아귀가 맞습니다. 앞으로 추가되는 대회부터 MAX+1로 올라갑니다.
ALTER TABLE runforce_contests ADD COLUMN weight_index INTEGER NOT NULL DEFAULT 1;
