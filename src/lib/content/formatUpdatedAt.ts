// D1 datetime('now') is UTC without a zone suffix. Make that explicit before formatting
// so build hosts in different time zones render the same KST timestamp.
export function formatUpdatedAt(value: string): string {
  const iso = value.includes("T") ? value : `${value.replace(" ", "T")}Z`;
  const date = new Date(iso);
  if (Number.isNaN(date.getTime())) return value;

  const parts = new Intl.DateTimeFormat("en-CA", {
    timeZone: "Asia/Seoul",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
    hour: "2-digit",
    minute: "2-digit",
    hourCycle: "h23",
  }).formatToParts(date);
  const get = (type: string) => parts.find((part) => part.type === type)?.value ?? "";
  return `${get("year")}-${get("month")}-${get("day")} ${get("hour")}:${get("minute")}`;
}

export function updatedAtDateTime(value: string): string {
  return value.includes("T") ? value : `${value.replace(" ", "T")}Z`;
}
